"""AI support assessment layered on top of the deterministic investigation.

The deterministic `InvestigationReport` stays authoritative: confidence,
evidence refs and the proposed action are copied from it unchanged and are
never taken from model output. The model only writes prose, and every
evidence citation it makes is checked against refs that really exist in the
gathered evidence; unknown citations are dropped and reported.
"""

import json
import re
from datetime import datetime, timezone
from typing import Any, Literal

from pydantic import BaseModel, ValidationError

from .investigation_analysis import InvestigationReport, RecommendedAction
from .llm_provider import LLMProvider, LLMUnavailableError

SYSTEM_PROMPT = """You are a support engineer assistant for a Kubernetes PaaS.
You receive a JSON investigation report produced by a deterministic analyzer.
Rules:
- Use ONLY facts present in the report. Never invent logs, metrics, events, \
timestamps, versions, pods or causes.
- Cite evidence only by exact "ref" strings that appear in the report.
- Clearly separate observed facts from inference. Use hedged language for \
inferences; the analyzer's confidence is a ceiling you must not exceed.
- Anything listed as missing or not collected is UNKNOWN, not proof of absence.
- You may recommend actions but you cannot authorize or execute anything. \
A rollback, if mentioned, is only a proposal pending policy and approval. \
Never say a rollback or fix has been performed.
- Label every assumption about customer impact as an assumption.
Reply with a single JSON object and nothing else, with these keys:
executive_summary (string),
likely_cause_explanation (string),
customer_impact {assessment (string), assumptions (list of strings)},
supporting_evidence (list of {statement, evidence_refs}),
contradictory_evidence (list of {statement, evidence_refs}),
missing_information (list of strings),
limitations (list of strings),
recommended_next_steps (list of strings),
customer_response (string, concise, customer-safe, no internal jargon, \
no promises of completed remediation)."""


class EvidenceStatement(BaseModel):
    statement: str
    evidence_refs: list[str] = []


class CustomerImpact(BaseModel):
    assessment: str
    assumptions: list[str] = []


class AIAssessment(BaseModel):
    executive_summary: str
    likely_cause_explanation: str
    customer_impact: CustomerImpact
    supporting_evidence: list[EvidenceStatement] = []
    contradictory_evidence: list[EvidenceStatement] = []
    missing_information: list[str] = []
    limitations: list[str] = []
    recommended_next_steps: list[str] = []
    customer_response: str


class DeterministicBasis(BaseModel):
    """Authoritative values copied from the deterministic analysis."""

    outcome: str
    confidence: Literal["low", "medium"] | None
    finding_keys: list[str]
    evidence_refs: list[str]
    recommended_actions: list[RecommendedAction]


class Grounding(BaseModel):
    known_ref_count: int
    dropped_refs: list[str]
    dropped_statements: int
    redacted_fields: list[str] = []


class ProviderInfo(BaseModel):
    name: str
    model: str | None


class AIAssessmentResponse(BaseModel):
    status: Literal["generated"] = "generated"
    ticket_id: int
    ticket_key: str
    generated_at: datetime
    ai_generated: bool = True
    provider: ProviderInfo
    assessment: AIAssessment
    deterministic_basis: DeterministicBasis
    grounding: Grounding
    notice: str = (
        "Narrative generated by an AI model from the deterministic investigation. "
        "Confidence and proposed actions come from the deterministic analysis. "
        "No remediation has been authorized or executed."
    )


class AIUnavailableResponse(BaseModel):
    status: Literal["provider_unavailable", "provider_invalid_response"]
    ai_generated: bool = False
    ticket_id: int
    ticket_key: str
    reason: str
    detail: str = (
        "No AI assessment was produced. The deterministic analysis is available "
        "at /investigation/analysis."
    )


class InvalidModelOutputError(Exception):
    pass


def collect_refs(node: Any) -> set[str]:
    """All `ref` values anywhere in the evidence tree."""
    found: set[str] = set()
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "ref" and isinstance(value, str):
                found.add(value)
            else:
                found |= collect_refs(value)
    elif isinstance(node, list):
        for item in node:
            found |= collect_refs(item)
    return found


def _report_refs(report: InvestigationReport) -> set[str]:
    return collect_refs(report.evidence.model_dump(mode="json"))


def build_user_prompt(report: InvestigationReport) -> str:
    return (
        "Investigation report (authoritative):\n"
        + report.model_dump_json(indent=1)
    )


def _extract_json(text: str) -> dict:
    cleaned = text.strip()
    fenced = re.match(r"^```(?:json)?\s*(.*?)\s*```$", cleaned, re.DOTALL)
    if fenced:
        cleaned = fenced.group(1)
    try:
        data = json.loads(cleaned)
    except json.JSONDecodeError:
        start, end = cleaned.find("{"), cleaned.rfind("}")
        if start == -1 or end <= start:
            raise InvalidModelOutputError("Model output was not valid JSON.")
        try:
            data = json.loads(cleaned[start : end + 1])
        except json.JSONDecodeError as exc:
            raise InvalidModelOutputError("Model output was not valid JSON.") from exc
    if not isinstance(data, dict):
        raise InvalidModelOutputError("Model output was not a JSON object.")
    return data


# Phrases asserting remediation already happened; the AI cannot know this.
_EXECUTED_CLAIM = re.compile(
    r"\b(has|have|was|were|been|already)\s+(been\s+)?"
    r"(rolled back|rolled-back|reverted|fixed|resolved|remediated|restored)\b",
    re.IGNORECASE,
)


def _ground(
    assessment: AIAssessment, known: set[str]
) -> tuple[AIAssessment, Grounding]:
    dropped_refs: list[str] = []
    dropped_statements = 0

    def clean(items: list[EvidenceStatement]) -> list[EvidenceStatement]:
        nonlocal dropped_statements
        kept = []
        for item in items:
            valid = [r for r in item.evidence_refs if r in known]
            dropped_refs.extend(r for r in item.evidence_refs if r not in known)
            if not valid:
                dropped_statements += 1
                continue
            kept.append(EvidenceStatement(statement=item.statement, evidence_refs=valid))
        return kept

    assessment.supporting_evidence = clean(assessment.supporting_evidence)
    assessment.contradictory_evidence = clean(assessment.contradictory_evidence)

    redacted: list[str] = []
    note = (
        "[Removed: AI text claimed remediation was completed, which is not "
        "supported. No action has been executed.]"
    )
    for field in ("executive_summary", "likely_cause_explanation", "customer_response"):
        if _EXECUTED_CLAIM.search(getattr(assessment, field)):
            setattr(assessment, field, note)
            redacted.append(field)

    return assessment, Grounding(
        known_ref_count=len(known),
        dropped_refs=sorted(set(dropped_refs)),
        dropped_statements=dropped_statements,
        redacted_fields=redacted,
    )


def _basis(report: InvestigationReport) -> DeterministicBasis:
    analysis = report.analysis
    rank = {"low": 0, "medium": 1}
    confidence = None
    if analysis.findings:
        confidence = min((f.confidence for f in analysis.findings), key=rank.get)
    refs = sorted(
        {r for f in analysis.findings for r in f.evidence_refs}
        | {r for a in analysis.recommended_actions for r in a.evidence_refs}
    )
    return DeterministicBasis(
        outcome=analysis.outcome,
        confidence=confidence,
        finding_keys=[f.key for f in analysis.findings],
        evidence_refs=refs,
        recommended_actions=analysis.recommended_actions,
    )


def generate_assessment(
    report: InvestigationReport, provider: LLMProvider
) -> AIAssessmentResponse:
    """Raises LLMUnavailableError or InvalidModelOutputError on failure."""
    raw = provider.complete(SYSTEM_PROMPT, build_user_prompt(report))
    try:
        assessment = AIAssessment.model_validate(_extract_json(raw))
    except ValidationError as exc:
        raise InvalidModelOutputError(
            "Model output did not match the required structure."
        ) from exc

    assessment, grounding = _ground(assessment, _report_refs(report))
    return AIAssessmentResponse(
        ticket_id=report.ticket_id,
        ticket_key=report.ticket_key,
        generated_at=datetime.now(timezone.utc),
        provider=ProviderInfo(name=provider.name, model=provider.model),
        assessment=assessment,
        deterministic_basis=_basis(report),
        grounding=grounding,
    )


